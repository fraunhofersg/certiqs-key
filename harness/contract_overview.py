r"""Motivation: one entry point to six contracts.

A reader new to the repository meets six contract PDFs and no page that says
which results matter, in what order the modules build on each other, or where
to start. The overview PDF is that page: an authored introduction with
reading paths (`spec/overview/intro.tex`) and a
generated part, `spec/overview/chain.tex`: the main results of every contract
in module dependency order, each with its summary and a link to its statement,
and the module map. The generated part is written here from the claim files
and `spec/modules.yaml`, so a result that gains or loses `prominence: main`, a
new summary or a new number shows up without a hand edit.

`spec/overview/overview.tex` is the generated frame (preamble, `\input` of
the authored introduction); the introduction decides where the generated part
goes by `\input{chain}`. The module map is `spec/module-graph.dot`, rendered to
PDF for this page.
"""

from __future__ import annotations

from pathlib import Path

from harness.check_claims import (
    XREF_RE,
    Repo,
    contract_of,
    link_target,
    load_yaml_mapping,
    strip_comments,
)
from harness.contract_navigation import (
    KIND_WORD,
    LINK_RE,
    claim_anchor,
    tex_mapped,
    tex_text,
    tex_title,
    xref_title,
)
from harness.contract_render import preamble
from harness.contract_structure import contract_sections

OVERVIEW_DIR = Path("spec") / "overview"
#: The module map as the overview includes it (rendered from spec/module-graph.dot).
MODULE_MAP_PDF = Path("spec") / "module-graph.pdf"


def core_order(root: Path, repo: Repo) -> list[str]:
    """Return the core modules present, dependencies before their dependents.

    The order is `spec/modules.yaml`'s declared `depends_on` among the cores
    that have a `module.yaml`, ties broken by the registry's order; a core the
    registry does not list comes last, alphabetically.
    """
    present = sorted(mid for mid in repo.modules if "/" not in mid)
    registry = root / "spec" / "modules.yaml"
    listed: list[tuple[str, list[str]]] = []
    if registry.is_file():
        for core in load_yaml_mapping(registry.read_text(encoding="utf-8")).get(
                "cores", []) or []:
            if isinstance(core, dict) and str(core.get("id")) in present:
                listed.append((str(core["id"]),
                               [str(dep) for dep in core.get("depends_on") or []]))
    order: list[str] = []
    remaining = dict(listed)
    while remaining:
        ready = [mid for mid, deps in remaining.items()
                 if all(dep in order or dep not in remaining for dep in deps)]
        if not ready:                        # a cycle: keep the registry's order
            ready = list(remaining)
        order.append(ready[0])
        remaining.pop(ready[0])
    return order + [mid for mid in present if mid not in order]


def contract_link(core: str, claim_id: str, text: str) -> str:
    """Link text to a claim's named destination in its contract PDF."""
    return (f"\\hyperref{{../modules/{core}/contract.pdf}}{{}}"
            f"{{{claim_anchor(claim_id)}}}{{{text}}}")


def overview_plain(repo: Repo, numbers: dict[str, str], text: str,
                   module_id: str) -> str:
    """Render a summary with its ``[[...]]`` links pointing into the contracts."""
    out: list[str] = []
    position = 0
    text = " ".join(text.split())
    for match in LINK_RE.finditer(text):
        out.append(tex_mapped(text[position:match.start()]))
        target = link_target(repo, module_id, match.group(1))
        if target is None:
            out.append(tex_mapped(match.group(0)))
        else:
            shown = (tex_text(target.short_id) if target.short_id else
                     f"{KIND_WORD.get(target.kind, 'Claim')}~"
                     f"{numbers.get(target.claim_id, '')}".rstrip("~"))
            out.append(contract_link(target.core, target.claim_id, shown))
        position = match.end()
    out.append(tex_mapped(text[position:]))
    return "".join(out)


def chain_tex(root: Path, repo: Repo) -> str:
    """Render the generated part: the main results by module, then the module map."""
    cores = core_order(root, repo)
    numbers: dict[str, str] = {}
    structures = {}
    for core in cores:
        structures[core] = contract_sections(repo, core)
        numbers.update(structures[core].numbers())
    out = ["% GENERATED by harness/assemble_contract.py --all; do not edit.\n",
           "\\section*{Main results, module by module}\n",
           "\\noindent Each contract's main results, the modules in dependency "
           "order (a module after every module it builds on). A heading opens the "
           "statement in its contract.\n"]
    for core in cores:
        meta = repo.modules[core].meta
        title = tex_text(str(meta.get("title", core)))
        version = tex_text(str(meta.get("version", "")))
        out.append(f"\n\\subsection*{{\\href{{../modules/{core}/contract.pdf}}"
                   f"{{{title}}}}}\n\\noindent{{\\small version {version}, "
                   f"\\href{{../modules/{core}/digest.pdf}}{{statements digest}}}}"
                   "\\par\\smallskip\n")
        mains = [cid for cid in structures[core].claims()
                 if cid in repo.claims
                 and repo.claims[cid].header.get("prominence") == "main"]
        if not mains:
            out.append("\\noindent No claim of this contract is marked as a main "
                       "result yet.\n")
            continue
        for cid in mains:
            claim = repo.claims[cid]
            heading = (f"{KIND_WORD.get(claim.kind, 'Claim')}~{numbers[cid]} "
                       f"({tex_title(str(claim.header.get('title', claim.label)))})")
            summary = str(claim.header.get("summary") or "")
            link = contract_link(core, cid, heading)
            out.append(f"\\par\\medskip\\noindent\\textbf{{{link}}}"
                       f"\\par\\nopagebreak\\noindent "
                       f"{overview_plain(repo, numbers, summary, claim.module_id)}\n")
    if (root / "spec" / "modules.yaml").is_file():   # the map's source
        out.append("\n\\section*{The module map}\n"
                   "\\noindent An arrow points from a module to a module it may build "
                   "on (its declared dependencies, not individual proof edges); a "
                   "dashed box is a module without claims yet.\\par\\medskip\n"
                   "\\noindent\\includegraphics[width=\\linewidth]"
                   f"{{../{MODULE_MAP_PDF.name}}}\n")
    return "".join(out)


def intro_xrefs(repo: Repo, intro: str) -> str:
    r"""Return one ``\DeclareXref`` line per claim the introduction cites.

    Generated like a contract's, so a cited claim's new title or kind reaches
    the overview without a hand edit; a target that is no claim is left out
    and ``\xref`` prints it as unresolved.
    """
    cited = sorted({match.group(1).strip()
                    for match in XREF_RE.finditer(strip_comments(intro))})
    lines = []
    for cid in cited:
        claim = repo.claims.get(cid)
        if claim is None:
            continue
        title = xref_title(str(claim.header.get("title", claim.label)))
        lines.append(f"\\DeclareXref{{{cid}}}{{{KIND_WORD.get(claim.kind, 'Claim')}}}"
                     f"{{{title}}}{{../modules/{contract_of(cid)}/contract.pdf}}\n")
    return "".join(lines)


def overview_tex(repo: Repo, intro: str) -> str:
    """Render the generated frame of the overview: preamble and the introduction."""
    return (preamble("CERTIQS-KEY -- overview of the contracts", macros="../macros",
                     index=False)
            + intro_xrefs(repo, intro)
            + "\n\\begin{document}\n\\input{intro}\n\\end{document}\n")


def overview_sources(root: Path, repo: Repo) -> dict[Path, str]:
    """Return the generated overview files, keyed by path."""
    directory = root / OVERVIEW_DIR
    intro = directory / "intro.tex"
    text = intro.read_text(encoding="utf-8") if intro.is_file() else ""
    return {directory / "overview.tex": overview_tex(repo, text),
            directory / "chain.tex": chain_tex(root, repo)}
