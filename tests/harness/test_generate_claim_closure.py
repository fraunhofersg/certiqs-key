"""The shipped claim-closure table is current against the claim files.

MOTIVATION, AND THE ERROR CLASS IT CATCHES. ``src/certiqs_key/domain/
claim_closure.json`` is what a run record reads to name the claim graph its
number rests on (PRINCIPLES.md section 2.1, spec/architecture.md 4.4) and the
statistics version it consumed, and the assumption and claim text a key-rate
report quotes. It is generated by ``harness/generate_claim_closure.py`` from
the claim files; a claim edit, a summary edit, a module version bump or a new
claim root that is not regenerated would ship a manifest naming a stale
closure, a version no longer accepted, or a report quoting text the contract no
longer has. This runs the generator's ``--check`` on the tree, shows that
``--check`` does see a stale table and names the blocks that differ (a check
that always passes would check nothing), and holds the generator's text fields,
its link normalisation and its refusals to the `format` fixture.

The tools run in a subprocess: ``tests/harness/`` is itself a package named
``harness``, so an in-process import would find it rather than the tools.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
FORMAT = REPO_ROOT / "tests" / "harness" / "fixtures" / "format"


def run(*args: str) -> subprocess.CompletedProcess[str]:
    """Run a command from the repository root, where ``harness`` is the tool."""
    return subprocess.run(
        [sys.executable, *args],
        cwd=REPO_ROOT, capture_output=True, text=True, check=False,
        encoding="utf-8",
    )


def fixture_copy(tmp_path: Path) -> Path:
    """Return a scratch copy of the `format` fixture."""
    target = tmp_path / "repo"
    shutil.copytree(FORMAT, target)
    return target


def build(repo: Path, roots: tuple[str, ...], limitations: tuple[str, ...],
          cited: tuple[str, ...] = ()) -> subprocess.CompletedProcess[str]:
    """Run ``build_table`` on ``repo`` with the given declarations; print JSON."""
    script = textwrap.dedent(
        f"""
        import json
        from pathlib import Path
        from harness.check_claims import load_repo
        from harness.generate_claim_closure import build_table
        repo = load_repo(Path({str(repo)!r}))
        try:
            table = build_table(repo, roots={roots!r}, limitations={limitations!r},
                                cited={cited!r})
        except ValueError as exc:
            print("REFUSED: " + str(exc))
        else:
            print(json.dumps(table, sort_keys=True, ensure_ascii=True))
        """
    )
    return run("-c", script)


def last_json(result: subprocess.CompletedProcess[str]) -> dict[str, Any]:
    assert result.returncode == 0, result.stdout + result.stderr
    line = result.stdout.strip().splitlines()[-1]
    assert not line.startswith("REFUSED"), line
    table = json.loads(line)
    assert isinstance(table, dict)
    return table


def test_checked_in_table_is_current() -> None:
    result = run("-m", "harness.generate_claim_closure", "--check")
    assert result.returncode == 0, result.stdout + result.stderr


def test_the_table_carries_every_assumption_with_its_key_text_and_anchor() -> None:
    """The run record marks a row never verified from this map.

    Each assumption of the format fixture is listed with its owner, the
    machine key its owner's interface.yaml gives it and its verification
    header field, so the record needs no hand list of its own; and, for the
    key-rate report, its plain text, statuses, contract anchor,
    generated verification sentence and emission rules. A field the header
    lacks (here `refines`) is ``null``; an absent ``presupposes`` is the
    empty list.
    """
    table = last_json(build(FORMAT, roots=("core-a/thm:bound",), limitations=()))
    assert table["assumptions"]["A-LEAF"] == {
        "owner": "core-a/ass:leaf",
        "machine_key": "leaf_nonnegative",
        "verification": "never",
        "verification_sentence": "The engine does not verify this assumption; a "
                                 "run that rests on it records it as unverified.",
        "title": "Nonnegative second coordinate",
        "summary": "The second coordinate of every base object is nonnegative.",
        "user_statement": "Every pair you declare has a nonnegative second "
                          "coordinate.",
        "category": "source",
        "presupposes": [],
        "affects": ["secrecy"],
        "refines": None,
        "status": "accepted",
        "effective_status": "accepted",
        "contract": {"pdf": "spec/modules/core-a/contract.pdf",
                     "anchor": "claim-core-a/ass:leaf"},
        "emission": {},
    }
    assert table["roots"]["core-a/thm:bound"]["assumptions"] == {
        "A-LEAF": "core-a/ass:leaf"
    }


def test_an_assumptions_presupposes_is_carried_beside_its_category(
    tmp_path: Path,
) -> None:
    """A run-tier guard reads the roles a premise's text presupposes from here.

    The table carries the header's list
    as written, so the guard needs no copy of the claim headers; and the
    category vocabulary's order, ``laboratory`` after ``receiver``, is the
    report's grouping order.
    """
    repo = fixture_copy(tmp_path)
    path = repo / "spec" / "modules" / "core-a" / "claims" / "ass-leaf.tex"
    text = path.read_text(encoding="utf-8")
    path.write_text(text.replace("% category: source\n",
                                 "% category: laboratory\n"
                                 "% presupposes: [sends, setting]\n", 1),
                    encoding="utf-8", newline="\n")
    table = last_json(build(repo, roots=("core-a/thm:bound",), limitations=()))
    row = table["assumptions"]["A-LEAF"]
    assert row["presupposes"] == ["sends", "setting"]
    assert row["category"] == "laboratory"
    assert table["category_order"][:3] == ["source", "receiver", "laboratory"]


def test_links_in_carried_text_are_full_targets_and_every_target_is_carried() -> None:
    table = last_json(build(FORMAT, roots=("core-b/prop:cross",),
                            limitations=("core-a/rem:tight",)))
    claims = table["claims"]
    # A bare label is written as the full id it resolves to; a full id and a
    # short id stay as they are.
    assert claims["core-a/rem:tight"]["summary"] == (
        "The bound of [[core-a/thm:bound]] is attained at y = 0."
    )
    assert claims["core-b/prop:cross"]["summary"] == (
        "A consumer's value is capped at one, by [[core-a/thm:bound]] under "
        "[[A-LEAF]]."
    )
    # Whitespace of a folded summary is collapsed, and its link made full.
    assert claims["core-a/thm:bound"]["summary"].startswith(
        "The first coordinate of a base object ([[core-a/def:object]]) is at"
    )
    assert claims["core-b/prop:cross"]["kind_word"] == "Proposition"
    assert claims["core-b/prop:cross"]["contract"] == {
        "pdf": "spec/modules/core-b/contract.pdf",
        "anchor": "claim-core-b/prop:cross",
    }
    # The root, the limitation, the assumption owner and every claim a carried
    # text links to, transitively (thm:bound links def:object).
    assert set(claims) == {"core-b/prop:cross", "core-a/rem:tight",
                           "core-a/ass:leaf", "core-a/thm:bound",
                           "core-a/def:object"}
    assert table["limitations"] == ["core-a/rem:tight"]
    assert table["category_order"][:2] == ["source", "receiver"]


def test_a_claims_user_statement_is_carried_beside_its_summary(
    tmp_path: Path,
) -> None:
    """The report presents its security statement through these.

    A claim of any kind but a definition may carry a plain reading; every
    entry of the ``claims`` block carries it, ``null`` where the claim has
    none, its links written as full targets and their targets carried in turn
    (here rem:tight, reached only through the reading).
    """
    repo = fixture_copy(tmp_path)
    path = repo / "spec" / "modules" / "core-a" / "claims" / "thm-bound.tex"
    text = path.read_text(encoding="utf-8")
    path.write_text(text.replace(
        "% lean:\n",
        "% user_statement: >-\n"
        "%   Your first coordinate is at most one while [[A-LEAF]] holds;\n"
        "%   see [[rem:tight]].\n% lean:\n", 1), encoding="utf-8", newline="\n")
    claims = last_json(build(repo, roots=("core-a/thm:bound",),
                             limitations=()))["claims"]
    assert claims["core-a/thm:bound"]["user_statement"] == (
        "Your first coordinate is at most one while [[A-LEAF]] holds; see "
        "[[core-a/rem:tight]]."
    )
    assert claims["core-a/def:object"]["user_statement"] is None
    assert claims["core-a/rem:tight"]["user_statement"] is None
    assert claims["core-a/ass:leaf"]["user_statement"] == (
        "Every pair you declare has a nonnegative second coordinate."
    )


def test_a_declared_id_that_is_no_claim_is_refused(tmp_path: Path) -> None:
    for roots, limitations, cited, what in (
        (("core-a/thm:nowhere",), (), (), "claim roots"),
        ((), ("core-a/rem:nowhere",), (), "limitation claims"),
        ((), (), ("core-a/req:nowhere",), "cited claims"),
    ):
        result = build(FORMAT, roots, limitations, cited)
        assert result.returncode == 0, result.stderr
        assert f"REFUSED: {what} that are not claims" in result.stdout, result.stdout
    # The same refusal through the command: a tree with a table but without
    # the declared roots writes nothing.
    repo = fixture_copy(tmp_path)
    table = repo / "src" / "certiqs_key" / "domain" / "claim_closure.json"
    table.parent.mkdir(parents=True)
    table.write_bytes(b"{}\n")
    result = run("-m", "harness.generate_claim_closure", "--repo", str(repo))
    assert result.returncode == 1
    assert "that are not claims" in result.stderr
    assert "no table written" in result.stderr
    assert table.read_bytes() == b"{}\n"


def test_an_unresolved_link_in_a_carried_text_is_refused(tmp_path: Path) -> None:
    repo = fixture_copy(tmp_path)
    path = repo / "spec" / "modules" / "core-a" / "claims" / "rem-tight.tex"
    text = path.read_text(encoding="utf-8")
    path.write_text(text.replace("[[thm:bound]]", "[[thm:nowhere]]"),
                    encoding="utf-8", newline="\n")
    result = build(repo, roots=(), limitations=("core-a/rem:tight",))
    assert "REFUSED: core-a: the link [[thm:nowhere]]" in result.stdout, result.stdout


def test_emission_rules_are_read_in_both_shapes_and_another_is_refused(
    tmp_path: Path,
) -> None:
    repo = fixture_copy(tmp_path)
    interface = repo / "spec" / "modules" / "core-a" / "interface.yaml"
    base = interface.read_text(encoding="utf-8")
    for rule, expected in (
        ("  emission_rule:\n    A-LEAF: \"whenever the bound is wanted\"\n",
         {"core-a": "whenever the bound is wanted"}),
        ("  emission_rule:\n    always: [A-LEAF, A-RETIRED]\n",
         {"core-a": "always"}),
    ):
        interface.write_text(base + rule, encoding="utf-8", newline="\n")
        table = last_json(build(repo, roots=(), limitations=()))
        assert table["assumptions"]["A-LEAF"]["emission"] == expected
    for bad, key in (("    A-LEAF: 3\n", "A-LEAF"),
                     ("    always: [A-LEAF, every-round]\n", "always")):
        interface.write_text(base + "  emission_rule:\n" + bad,
                             encoding="utf-8", newline="\n")
        result = build(repo, roots=(), limitations=())
        assert f"REFUSED: core-a: assumption_ledger.emission_rule['{key}']" in (
            result.stdout), result.stdout


def test_check_reports_a_stale_table_and_names_the_blocks(tmp_path: Path) -> None:
    """A table differing from the claim files fails; the exact one passes.

    The exact table is the generator's own rendering of the tree, not the
    checked-in file, so this depends only on the generator and holds while
    the checked-in table is stale (another batch in flight); it needs a
    claim graph without check_claims errors, on which ``--check`` writes and
    compares nothing.
    """
    stale = tmp_path / "stale.json"
    exact = tmp_path / "exact.json"
    script = textwrap.dedent(
        f"""
        import json
        from pathlib import Path
        import harness.generate_claim_closure as tool
        from harness.check_claims import load_repo
        text = tool.render(tool.build_table(load_repo(Path({str(REPO_ROOT)!r}))))
        Path({str(exact)!r}).write_bytes(text.encode("utf-8"))
        table = json.loads(text)
        table["module_versions"]["statistics"] = "0.0.0"
        first = sorted(table["claims"])[0]
        table["claims"][first]["summary"] = "an edited summary"
        Path({str(stale)!r}).write_bytes(tool.render(table).encode("utf-8"))
        codes = []
        for target in ({str(stale)!r}, {str(exact)!r}):
            tool.OUTPUT = Path(target)
            codes.append(tool.main(["--check"]))
        print(codes)
        """
    )
    result = run("-c", script)
    assert result.returncode == 0, result.stdout + result.stderr
    assert result.stdout.strip().splitlines()[-1] == "[1, 0]", result.stdout
    assert "is stale" in result.stderr
    assert "differing blocks: claims, module_versions" in result.stderr


def test_assemble_all_runs_the_generator_where_a_table_ships(tmp_path: Path) -> None:
    """``assemble_contract --all`` regenerates the table, so a summary edit reaches it.

    The fixture declares none of the engine's roots, so with a table present
    the step runs and refuses (which shows it ran); without one it is skipped.
    """
    repo = fixture_copy(tmp_path)

    def check() -> subprocess.CompletedProcess[str]:
        return run("-m", "harness.assemble_contract", "--all", "--no-pdf",
                   "--repo", str(repo))

    assert "claim_closure" not in (result := check()).stdout + result.stderr
    assert result.returncode == 0, result.stdout + result.stderr
    table = repo / "src" / "certiqs_key" / "domain" / "claim_closure.json"
    table.parent.mkdir(parents=True)
    table.write_bytes(b"{}\n")
    result = check()
    assert result.returncode == 1
    assert "claim roots that are not claims" in result.stderr
